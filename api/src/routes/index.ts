import { Router } from "express";
import type { AppContext } from "../app";
import { backupRouter } from "./backup";
import { cardsRouter } from "./cards";
import { costsRouter } from "./costs";
import { customersRouter } from "./customers";
import { demoEmails, demoGuard } from "./demo";
import { dashboardRouter } from "./dashboard";
import { deliveriesRouter } from "./deliveries";
import { importsRouter } from "./imports";
import { invoicesRouter, orderInvoiceRouter } from "./invoices";
import { ordersRouter } from "./orders";
import { paymentsRouter } from "./payments";
import { productsRouter } from "./products";
import { shopifyRouter } from "./shopify";
import { parseApps } from "../shopify/products";
import { shipmentRouter, shipmentsListRouter } from "./shipments";
import { reportsRouter } from "./reports";
import { requireUser } from "./require-user";
import { stockRouter } from "./stock";
import { storesRouter } from "./stores";
import { whatsappRouter } from "./whatsapp";

// Everything under /v1 except sign-in needs a signed-in owner.
export function createRoutes(ctx: AppContext): Router {
  const router = Router();
  router.use(requireUser(ctx.auth));
  router.use(demoGuard(ctx));
  router.get("/me", (req, res) => res.json({ user: { ...req.user, demo: demoEmails(ctx).includes(req.user!.email.toLowerCase()) } }));
  router.use("/stores", storesRouter(ctx.db));
  router.use("/dashboard", dashboardRouter(ctx.db));
  router.use("/backup", backupRouter(ctx.db));
  router.use("/reports", reportsRouter(ctx.db));
  router.use("/stores/:storeId/products", productsRouter(ctx.db));
  router.use("/stores/:storeId/customers", customersRouter(ctx.db));
  router.use("/stores/:storeId/missing-costs", costsRouter(ctx.db));
  router.use("/stores/:storeId/orders", ordersRouter(ctx.db, ctx.config));
  router.use("/stores/:storeId/orders/:orderId/invoice", orderInvoiceRouter(ctx.db));
  router.use("/stores/:storeId/orders/:orderId/delivery", deliveriesRouter(ctx.db));
  router.use("/stores/:storeId/orders/:orderId/card", cardsRouter(ctx.db, ctx.config));
  router.use("/stores/:storeId/orders/:orderId/shipment", shipmentRouter(ctx.db));
  router.use("/stores/:storeId/shipments", shipmentsListRouter(ctx.db));
  router.use("/stores/:storeId/import", importsRouter(ctx.db));
  router.use("/stores/:storeId/shopify", shopifyRouter(ctx.db, parseApps(ctx.config.SHOPIFY_APPS), ctx.fetch ?? fetch, ctx.lookup));
  router.use("/stores/:storeId/invoices", invoicesRouter(ctx.db));
  router.use("/stores/:storeId", paymentsRouter(ctx.db));
  router.use("/stores/:storeId", whatsappRouter(ctx.db));
  router.use("/stores/:storeId/stock", stockRouter(ctx.db));
  return router;
}
